/// Representation of an authentic, scientifically grounded psychology fact.
class PsychologyFact {
  final int id;
  final String title;
  final String category;
  final String fact;
  final String takeaway;
  final String emoji;

  const PsychologyFact({
    required this.id,
    required this.title,
    required this.category,
    required this.fact,
    required this.takeaway,
    this.emoji = '🧠',
  });

  Map<String, dynamic> toJson() => {
    'id': id,
    'title': title,
    'category': category,
    'fact': fact,
    'takeaway': takeaway,
    'emoji': emoji,
  };

  factory PsychologyFact.fromJson(Map<String, dynamic> json) => PsychologyFact(
    id: json['id'] as int? ?? 0,
    title: json['title'] as String? ?? 'Psychology Insight',
    category: json['category'] as String? ?? 'Human Behavior',
    fact: json['fact'] as String? ?? '',
    takeaway: json['takeaway'] as String? ?? '',
    emoji: json['emoji'] as String? ?? '🧠',
  );
}

