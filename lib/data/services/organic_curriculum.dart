OrganicQuestion _q(
  String prompt,
  String correct,
  String wrong1,
  String wrong2,
  String why,
) => OrganicQuestion(prompt, [correct, wrong1, wrong2], 0, why);
OrganicQuestion _mix(OrganicQuestion question, String salt) {
  var seed = salt.codeUnits.fold(7, (sum, value) => (sum * 31 + value) % 65521);
  final order = [0, 1, 2];
  for (var i = 2; i > 0; i--) {
    seed = (seed * 25173 + 13849) % 65521;
    final j = seed % (i + 1);
    final old = order[i];
    order[i] = order[j];
    order[j] = old;
  }
  return OrganicQuestion(
    question.prompt,
    order.map((i) => question.options[i]).toList(),
    order.indexOf(question.answer),
    question.explanation,
  );
}

